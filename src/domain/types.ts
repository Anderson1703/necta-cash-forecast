export type Scenario = 'conservative' | 'base' | 'optimistic';
export type Source = 'confirmed' | 'assumed';
export type CashEvent = {
  id: string; date: string; amount: number; direction: 'in' | 'out';
  source: Source; category: 'cash_sales' | 'receivable' | 'expense' | 'payable';
  description: string;
  /** Explicitly mark whether this cash movement is already in the opening balance. */
  includedInOpeningBalance?: boolean;
};
export type Receivable = {
  id: string; customer: string; pendingAmount: number; dueDate: string;
  onTimePayments: number; totalPayments: number; averageLateDays: number;
  /** Optional manually verified date for a severely overdue invoice */
  expectedDateOverride?: string;
};
export type Obligation = {
  id: string; date: string; amount: number; description: string;
  source: Source; category: 'expense' | 'payable';
  /** Already settled before the opening balance cutoff; never emit as future cash. */
  paidBeforeCutoff?: number;
  /** Stable recurrence identity, if generated by a recurring rule. */
  recurrenceId?: string;
  /** Period of the obligation, e.g. 2026-06. */
  periodKey?: string;
};
export type ObligationPayment = {
  id: string; obligationId: string; amount: number; date: string;
  /** A payment at/before cutoff belongs in paidBeforeCutoff, not here. */
  includedInOpeningBalance: false;
};
export type OpeningBalance = {
  /** Explicit decision at the cutoff immediately before startDate. */
  amount: number;
  asOfDate: string;
  status: 'provisional' | 'verified';
  source: 'reconstructed' | 'stored_snapshot' | 'bank_verified' | 'cash_count';
  /** Server-side evidence reference; not proof by itself. */
  evidenceId?: string;
};
export type BalanceSensitivity = {
  reference: 'stored' | 'reconstructed';
  openingBalance: number;
  scenarios: Record<Scenario, { endingBalance: number; minimumBalance: number; firstShortfallDate: string | null }>;
};
export type BalanceAssessment = {
  selected: OpeningBalance;
  reconciled: boolean;
  difference: number;
  alternatives: BalanceSensitivity[];
  note: string;
};
export type ForecastInput = {
  startDate: string; days: number; currency: 'COP';
  storedBalance: number; reconstructedBalance: number;
  /** Optional explicit opening balance; omitted means provisional reconstructed. */
  openingBalance?: OpeningBalance;
  receivables: Receivable[]; obligations: Obligation[];
  /** Future payments applied to specific obligations, not generic future events. */
  obligationPayments?: ObligationPayment[];
  dailyCashExpenses: number; fortnightDates: string[];
  /** Case-study baseline cash sales, not additional to confirmed daily sales. */
  baselineSales: { weekday: number; fridaySaturday: number };
  /** Future confirmed cash movements, with includedInOpeningBalance explicitly false. */
  confirmedFutureEvents?: CashEvent[];
  coverageEstimate?: { min: number; max: number };
};
export type DailyPoint = {
  date: string; openingBalance: number; inflows: number; outflows: number;
  closingBalance: number; events: CashEvent[];
};
export type ScenarioResult = { scenario: Scenario; days: DailyPoint[]; endingBalance: number; minimumBalance: number; firstShortfallDate: string | null };
export type Recommendation = { code: string; priority: 'high' | 'medium'; message: string; evidence: string[] };
export type QualityFinding = { code: 'COVERAGE_UNKNOWN' | 'LOW_COVERAGE' | 'PARTIAL_COVERAGE' | 'PROVISIONAL_OPENING' | 'BALANCE_MISMATCH' | 'MISSING_PAYMENT_HISTORY' | 'INFERRED_OBLIGATIONS'; severity: 'high' | 'medium'; detail: string };
export type DataQualityAssessment = { level: 'low' | 'medium' | 'high'; findings: QualityFinding[]; method: string };
export type ForecastAlert = { id: string; code: 'CASH_SHORTFALL' | 'DATA_QUALITY_LOW' | 'REVIEW_LARGE_OBLIGATION'; severity: 'critical' | 'warning' | 'info'; scenario?: Scenario; date: string; message: string; evidence: string[] };
export type ForecastResult = { currency: 'COP'; startDate: string; days: number; balanceDiscrepancy: number; balanceAssessment: BalanceAssessment; qualityWarnings: string[]; dataQuality: DataQualityAssessment; alerts: ForecastAlert[]; scenarios: Record<Scenario, ScenarioResult>; recommendations: Recommendation[]; assumptions: string[] };
